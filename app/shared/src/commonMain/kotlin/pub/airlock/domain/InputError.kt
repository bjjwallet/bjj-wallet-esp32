package pub.airlock.domain

/** Stable validation codes let the UI translate errors without exposing platform exception text. */
enum class InputError {
    HARDWARE_PIN_REQUIRED,
    INVALID_WALLET_NAME,
    HARDWARE_PIN_SETUP_REQUIRED,
    HARDWARE_PIN_FORMAT,
    HARDWARE_PIN_LOCKED,
    HARDWARE_BUSY,
    HARDWARE_APPROVAL_REQUIRED,
    HARDWARE_FAILURE,
    PIN_LENGTH,
    PIN_CHARACTERS,
    PIN_SAME,
    CURRENT_PIN,
    INCORRECT_PIN,
    DESTINATION_REQUIRED,
    AMOUNT_POSITIVE,
    INVALID_AMOUNT,
    DECIMAL_PLACES,
    INSUFFICIENT_BALANCE,
    INSUFFICIENT_FEE_BALANCE,
    INVALID_QUOTE,
    HTTPS_REQUIRED,
    INVALID_SERVER,
    INVALID_LANGUAGE,
    INTEGRATION_UNAVAILABLE,
    DEVICE_DISCONNECTED,
    VAULT_OPEN,
    OPERATION_FAILED,
    PUBLIC_DATA_INVALID,
    PUBLIC_DATA_INCOMPLETE,
    PUBLIC_DATA_SYNC_REQUIRED,
    PUBLIC_DATA_CHANGED,
    ADDRESS_INDEX_EXHAUSTED,
    BLUETOOTH_PERMISSION,
    BLUETOOTH_UNAVAILABLE,
    INVALID_API_KEY,
    API_KEY_REQUIRED,
    PROVIDER_UNAVAILABLE,
    PROVIDER_RATE_LIMITED,
    NETWORK_UNSUPPORTED,
    NETWORK_MISMATCH,
    INVALID_DESTINATION,
    TRANSACTION_REJECTED,
    SUBMISSION_PENDING,
    XRPL_TRUSTLINE_REQUIRED,
    MONERO_SCANNER_UNAVAILABLE,
    MONERO_SCAN_PENDING,
    MONERO_SYNC_REJECTED,
    MONERO_KEY_IMAGES_UNAVAILABLE,
    MONERO_VIEW_SYNC_REQUIRED,
    MONERO_SCAN_PAUSED,
    MONERO_SCAN_TIMEOUT,
    MONERO_CONNECTION_FAILED,
    MONERO_PAIRING_FAILED,
}

class InputException(val reason: InputError) : IllegalArgumentException(reason.name)

fun requireInput(condition: Boolean, reason: InputError) {
    if (!condition) throw InputException(reason)
}

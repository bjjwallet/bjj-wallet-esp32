#!/usr/bin/env python3
"""Format owned source files without touching generated code or dependencies."""

import argparse
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
ROOTS = (
    "app/shared/src",
    "app/androidApp/src",
    "app/iosApp/AirLock",
    "app/iosApp/AirLockUITests",
    "app/scripts",
    "hardware/core",
    "hardware/hardware",
    "hardware/ui",
    "hardware/js",
    "hardware/esp32/core",
    "hardware/esp32/hardware",
    "hardware/esp32/ui",
    "hardware/esp32/idf_components",
    "hardware/esp32/tests",
    "hardware/esp32/tools",
    "hardware/esp32/firmware/main",
    "hardware/esp32/simulator",
    "hardware/esp32/monero_signer",
    "tools",
)
EXTENSIONS = {".kt", ".kts", ".cpp", ".hpp", ".h", ".c", ".py", ".swift", ".js", ".cjs", ".rs"}
EXCLUDED = {
    "vendor",
    "target",
    "assets",
    "fonts",
    "node_modules",
    "protocol-reference",
    "__pycache__",
}


def sources():
    command = ["rg", "--files", *ROOTS]
    for part in sorted(EXCLUDED):
        command.extend(["-g", f"!**/{part}/**"])
    result = subprocess.run(command, cwd=ROOT, check=True, capture_output=True, text=True)
    candidates = {ROOT / line for line in result.stdout.splitlines()}
    candidates.update((ROOT / "app").glob("*.kts"))
    candidates.update((ROOT / "app/androidApp").glob("*.kts"))
    candidates.update((ROOT / "app/shared").glob("*.kts"))
    candidates.update((ROOT / "hardware").glob("*.py"))
    for path in sorted(candidates):
        if path.suffix not in EXTENSIONS or path.name == "TonWalletCode.kt":
            continue
        header = "\n".join(
            line.lower()
            for line in path.read_text(encoding="utf-8").splitlines()[:12]
            if line.lstrip().startswith(("//", "#", "/*", "*"))
        )
        if (
            "generated by" in header
            or "do not edit" in header
            or "automatically generated" in header
        ):
            continue
        yield path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Check formatting without rewriting files."
    )
    parser.add_argument(
        "--ktfmt", default=os.environ.get("KTFMT_JAR"), help="Path to ktfmt 0.54 JAR."
    )
    parser.add_argument("--clang-format", default="clang-format")
    parser.add_argument("--prettier", default="prettier")
    args = parser.parse_args()
    if not args.ktfmt:
        parser.error("Pass --ktfmt or set KTFMT_JAR to the formatter JAR.")

    grouped = {}
    for path in sources():
        grouped.setdefault(path.suffix, []).append(str(path.relative_to(ROOT)))

    def run(command, extensions):
        files = sorted(path for extension in extensions for path in grouped.get(extension, []))
        if not files:
            return
        print(f"{command[0]}: {len(files)} source files", flush=True)
        result = subprocess.run([*command, *files], cwd=ROOT)
        if result.returncode:
            raise SystemExit(result.returncode)

    run(
        ["java", "-jar", args.ktfmt, "--kotlinlang-style", "--do-not-remove-unused-imports"]
        + (["--dry-run", "--set-exit-if-changed"] if args.check else []),
        {".kt", ".kts"},
    )
    run(
        [args.clang_format, "--style=file"] + (["--dry-run", "--Werror"] if args.check else ["-i"]),
        {".cpp", ".hpp", ".h", ".c"},
    )
    run(
        [sys.executable, "-m", "black", "--line-length", "100"]
        + (["--check"] if args.check else []),
        {".py"},
    )
    run([args.prettier, "--check" if args.check else "--write"], {".js", ".cjs"})
    run(
        [
            "xcrun",
            "swift-format",
            "lint" if args.check else "format",
            "--configuration",
            ".swift-format",
        ]
        + (["--strict"] if args.check else ["--in-place"]),
        {".swift"},
    )
    run(["rustfmt", "--edition", "2021"] + (["--check"] if args.check else []), {".rs"})


if __name__ == "__main__":
    main()

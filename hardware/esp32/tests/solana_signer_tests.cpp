#include "core/solana_signer.hpp"
#include "core/json_memory.hpp"
#include "core/solana_signing_catalog.hpp"
#include "cJSON.h"
#include <cstdlib>
#include <fstream>
#include <iostream>

using namespace airlock;

namespace {
struct TestRandom : crypto::RandomSource {
    bool fill(crypto::Output output) override {
        for (std::size_t i = 0; i < output.size; ++i)
            output.data[i] = std::rand() % 256;
        return true;
    }
};
void check(bool result, const char* message) {
    if (!result) {
        std::cerr << message << '\n';
        std::exit(1);
    }
}
std::string replace(std::string text, std::string_view before, std::string_view after) {
    text.replace(text.find(before), before.size(), after);
    return text;
}
} // namespace

int main(int argc, char** argv) {
    init_json();
    const std::string plan = R"({
        "network":"solana-mainnet",
        "wallet_id":"1111111111111111111111111111111111111111111111111111111111111111",
        "mode":"STANDARD",
        "sender":"GjJyeC1r2RgkuoCWMyPYkCWSGSGLcz266EaAkLA27AhL",
        "recipient":"CktRuQ2mttgRGkXJtyksdKHjUdc2C4TgDzyB98oEzy8",
        "path":"m/44'/501'/0'",
        "amount_atomic":"1250000000",
        "fee_atomic":"5000",
        "blockhash":"US517G5965aydkZ46HS38QLi7UQiSojurfbQfKCELFx"
    })";
    SolanaReview review;
    check(review_solana(plan, review) && review.amount == "1250000000", "review exact SOL amount");
    check(!review_solana(replace(plan, "solana-mainnet", "solana-devnet"), review),
          "reject different network");
    check(!review_solana(replace(plan, R"("fee_atomic":"5000")", R"("fee_atomic":"4000")"), review),
          "reject different base fee");
    check(!review_solana(replace(plan, "1250000000", "18446744073709551616"), review),
          "reject overflowing lamports");
    check(!review_solana(replace(plan, "501'/0'", "501'/0"), review), "reject a non-hardened path");
    crypto::Seed seed;
    check(crypto::wallet_core_seed("abandon abandon abandon abandon abandon abandon abandon "
                                   "abandon abandon abandon abandon about",
                                   "", seed) == crypto::HdError::None,
          "derive public test vector");
    const crypto::Bytes bytes{seed.value.data(), seed.value.size()};
    TestRandom random;
    std::string signature;
    check(!sign_solana(replace(plan, "501'/0'", "501'/1'"), bytes, random, signature),
          "reject a sender from another path");
    check(sign_solana(plan, bytes, random, signature), "sign native SOL");
    // Independent Ed25519 signature generated by Node/OpenSSL from the public test mnemonic.
    check(signature == "b972b067c5ba0426747dba3c8fd50cc9aa9f8262e1fc3e3c717d3c45de9b5948c00021d6c13"
                       "1ff2d3ba2c0fb8f99f1d0f8b255335e590e13608ce40d59233201",
          "match independent Solana wire format and signature");
    auto* vectors = cJSON_CreateArray();
    for (const auto& token : solana_signing_assets)
        for (bool create : {false, true}) {
            const auto rent = create ? (token.extensions ? 2192400U : 2039280U) : 0;
            auto request = replace(plan, R"("fee_atomic":"5000")",
                                   "\"fee_atomic\":\"" + std::to_string(5000 + rent) + "\"");
            request.insert(request.find('{') + 1, "\"asset\":\"" + std::string(token.symbol) +
                                                      "\",\"rent_atomic\":\"" +
                                                      std::to_string(rent) + "\",");
            check(review_solana(request, review) && review.symbol == token.symbol &&
                      review.decimals == token.decimals &&
                      review.fee_amount == std::to_string(5000 + rent),
                  "review token, decimals and SOL rent/fee");
            check(sign_solana(request, bytes, random, signature),
                  "sign each token with and without recipient ATA creation");
            auto fake = request;
            fake.insert(fake.find('{') + 1, "\"mint\":\"11111111111111111111111111111111\",");
            check(!review_solana(fake, review), "reject a mint supplied by the host");
            check(!review_solana(replace(request, "\"asset\":\"" + std::string(token.symbol) + "\"",
                                         "\"asset\":\"FAKE\""),
                                 review),
                  "reject unknown Solana tokens");
            if (create)
                check(!review_solana(replace(request,
                                             "\"rent_atomic\":\"" + std::to_string(rent) + "\"",
                                             "\"rent_atomic\":\"1\""),
                                     review),
                      "reject understated ATA rent");
            auto* row = cJSON_CreateObject();
            cJSON_AddStringToObject(row, "symbol", std::string(token.symbol).c_str());
            cJSON_AddNumberToObject(row, "rent", rent);
            cJSON_AddStringToObject(row, "signature", signature.c_str());
            cJSON_AddItemToArray(vectors, row);
        }
    if (argc == 2) {
        char* json = cJSON_Print(vectors);
        check(json != nullptr, "encode cross-platform token fixtures");
        std::ofstream(argv[1]) << json << '\n';
        json_free(json);
    }
    cJSON_Delete(vectors);
}

#!/usr/bin/env python3
"""Pin mobile token identities in the offline signer; no arbitrary contracts."""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOMAIN = ROOT.parents[1] / "app/shared/src/commonMain/kotlin/pub/airlock/domain"
COINS = {"Bnb": "bsc", "Classic": "ethereumclassic"}


def generate():
    source = (ROOT / "core/network_accounts.hpp").read_text()
    networks = {}
    for enum, name, native, chain, path in re.findall(
        r'\{\s*Network::(\w+)\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*(\d+)\s*,\s*crypto::Curve::Secp256k1\s*,\s*"([^"]+)"',
        source,
    ):
        if int(chain):
            networks[COINS.get(enum, enum.lower())] = (
                chain,
                name,
                native,
                path.rsplit("/", 1)[0] + "/",
            )
    tokens = re.findall(
        r'TokenDefinition\(\s*"([^"]+)",\s*"([^"]+)",\s*"[^"]+",\s*"([^"]+)",\s*"[^"]+"\s*(?:,\s*(\d+))?\s*,?\s*\)',
        (DOMAIN / "Stablecoins.kt").read_text(),
    )
    rows = []
    for coin, (chain, name, native, path) in networks.items():
        rows.append(f'    {{{chain}, "{native}", "", "{name}", "{native}", "{path}", 18}},')
    seen = set()
    for coin, symbol, contract, decimals in tokens:
        if coin not in networks:
            continue
        if (coin, symbol) in seen or not re.fullmatch("0x[0-9a-fA-F]{40}", contract):
            raise ValueError("Invalid or duplicate EVM asset: " + coin + ":" + symbol)
        seen.add((coin, symbol))
        chain, name, native, path = networks[coin]
        rows.append(
            f'    {{{chain}, "{symbol}", "{contract[2:].lower()}", "{name}", "{native}", "{path}", {decimals or 6}}},'
        )
    return (
        """// Generated by tools/generate_signing_catalog.py. Do not edit.
// SPDX-License-Identifier: GPL-3.0-or-later
#pragma once
#include <cstdint>
#include <string_view>
namespace airlock {
struct EvmSigningAsset {
    std::uint32_t chain_id;
    std::string_view symbol, contract, network_name, native_symbol, path_prefix;
    unsigned decimals;
};
inline constexpr EvmSigningAsset evm_signing_assets[] = {
"""
        + "\n".join(rows)
        + """
};
inline const EvmSigningAsset* evm_signing_asset(std::uint64_t chain, std::string_view symbol) {
    for (const auto& asset : evm_signing_assets)
        if (asset.chain_id == chain && asset.symbol == symbol) return &asset;
    return nullptr;
}
}
"""
    )


def generate_solana():
    source = (DOMAIN / "NetworkSettings.kt").read_text()
    programs = dict(re.findall(r'const val (classicProgram|extensionsProgram) = "([^"]+)"', source))
    symbols = re.search(r"val token2022Symbols = setOf\(([^)]*)\)", source)
    if not symbols or len(programs) != 2:
        raise ValueError("Missing Solana program identities")
    extensions = set(re.findall(r'"([^"]+)"', symbols[1]))
    tokens = re.findall(
        r'TokenDefinition\(\s*"solana",\s*"([^"]+)",\s*"[^"]+",\s*"([^"]+)",\s*"[^"]+"\s*(?:,\s*(\d+))?\s*,?\s*\)',
        (DOMAIN / "Stablecoins.kt").read_text(),
    )
    if len({symbol for symbol, _, _ in tokens}) != len(tokens):
        raise ValueError("Duplicate Solana asset")
    rows = []
    for symbol, mint, decimals in tokens:
        program = programs["extensionsProgram" if symbol in extensions else "classicProgram"]
        rows.append(
            f'    {{"{symbol}", "{mint}", "{program}", {decimals or 6}, {str(symbol in extensions).lower()}}},'
        )
    return (
        """// Generated by tools/generate_signing_catalog.py. Do not edit.
// SPDX-License-Identifier: GPL-3.0-or-later
#pragma once
#include <string_view>
namespace airlock {
struct SolanaSigningAsset {
    std::string_view symbol, mint, program;
    unsigned decimals;
    bool extensions;
};
inline constexpr SolanaSigningAsset solana_signing_assets[] = {
"""
        + "\n".join(rows)
        + """
};
inline const SolanaSigningAsset* solana_signing_asset(std::string_view symbol) {
    for (const auto& asset : solana_signing_assets)
        if (asset.symbol == symbol) return &asset;
    return nullptr;
}
}
"""
    )


def generate_native_tokens():
    tokens = re.findall(
        r'TokenDefinition\(\s*"([^"]+)",\s*"([^"]+)",\s*"[^"]+",\s*"([^"]+)",\s*"[^"]+"\s*(?:,\s*(\d+))?\s*,?\s*\)',
        (DOMAIN / "Stablecoins.kt").read_text(),
    )
    rows = [
        f'    {{"{coin}", "{symbol}", "{contract}", {decimals if decimals else 6}}},'
        for coin, symbol, contract, decimals in tokens
        if coin in {"cardano", "tron", "ripple", "stellar", "ton", "sui"}
    ]
    return (
        """// Generated by tools/generate_signing_catalog.py. Do not edit.
// SPDX-License-Identifier: GPL-3.0-or-later
#pragma once
#include <string_view>
namespace airlock {
struct NativeSigningToken { std::string_view network, symbol, contract; unsigned decimals; };
inline constexpr NativeSigningToken native_signing_tokens[] = {
"""
        + "\n".join(rows)
        + """
};
inline const NativeSigningToken* native_signing_token(std::string_view network, std::string_view symbol) {
    for (const auto& token : native_signing_tokens)
        if (token.network == network && token.symbol == symbol) return &token;
    return nullptr;
}
}
"""
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, generated in [
        ("evm", generate()),
        ("solana", generate_solana()),
        ("native", generate_native_tokens()),
    ]:
        target = ROOT / f"core/{name}_signing_catalog.hpp"
        if args.check:
            if target.read_text() != generated:
                raise SystemExit("Regenerate the signing catalog from the mobile catalog: " + name)
        else:
            target.write_text(generated)

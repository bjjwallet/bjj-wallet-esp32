#!/usr/bin/env python3
"""Project the app's network and token catalog into the firmware receive menu."""

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

ESP32 = Path(__file__).resolve().parents[1]
DOMAIN = ESP32.parents[1] / "app/shared/src/commonMain/kotlin/pub/airlock/domain"
APP_ICONS = ESP32.parents[1] / "app/shared/src/commonMain/composeResources/files/coins"
FIRMWARE_NAMES = {
    "tron": "TRON",
    "arbitrum": "Arbitrum One",
    "polygon": "Polygon PoS",
}


def quoted(text):
    return re.findall(r'"([^"]+)"', text)


def generate():
    coins = (DOMAIN / "CoinCatalog.kt").read_text()
    networks = re.findall(r'CoinDefinition\(\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)"', coins)
    if not networks or len(networks) != coins.count("CoinDefinition("):
        raise ValueError("Could not read every CoinDefinition")
    standalone = set(
        quoted(re.search(r"UtxoNetworks\.supported\s*\+\s*setOf\s*\((.*?)\)", coins, re.S)[1])
    )
    utxo = (DOMAIN / "UtxoTransactionPlan.kt").read_text()
    standalone.update(quoted(re.search(r"val\s+supported\s*=\s*setOf\s*\((.*?)\)", utxo, re.S)[1]))

    stablecoins = (DOMAIN / "Stablecoins.kt").read_text()
    # Every displayed asset needs a checked-in mobile icon as well as a board icon.
    for source in (coins, stablecoins):
        for icon in re.findall(r'"([^"\n]+\.(?:svg|png|jpg))"', source):
            if not (APP_ICONS / icon).is_file():
                raise ValueError(f"Missing app icon: {icon}")
    definitions = dict(
        re.findall(r'val\s+(\w+)\s*=\s*TokenDefinition\(\s*("[^"]+",\s*"[^"]+")', stablecoins)
    )
    listing = re.search(
        r"val\s+tokens\s*=\s*listOf\s*\((.*?)\n\s*\)\s*\n\s*fun\s+forNetwork", stablecoins, re.S
    )[1]
    tokens = defaultdict(list)
    for row in re.finditer(
        r'TokenDefinition\(\s*("[^"]+",\s*"[^"]+")|^\s*([A-Za-z_]\w*),\s*$', listing, re.M
    ):
        coin, symbol = quoted(row[1] or definitions[row[2]])
        tokens[coin].append((symbol, False))
    if sum(map(len, tokens.values())) != stablecoins.count("TokenDefinition(") - 1:
        raise ValueError("Could not read every registered token")

    pending_source = (DOMAIN / "PendingAssets.kt").read_text()
    if not re.search(r"val\s+tokens\s*=\s*emptyMap<", pending_source):
        pending = re.search(r"val\s+tokens\s*=\s*mapOf\s*\((.*)\)", pending_source, re.S)[1]
        for coin, symbols in re.findall(r'"([^"]+)"\s+to\s+listOf\(([^)]*)\)', pending):
            tokens[coin].extend((symbol, True) for symbol in quoted(symbols))

    known = {coin for coin, _, _ in networks}
    if (set(tokens) | standalone | FIRMWARE_NAMES.keys()) - known:
        raise ValueError("Catalog references an unknown network")
    icon_root = ESP32 / "ui/assets/currency_icons"
    board_icons = json.loads((icon_root / "board_catalog.json").read_text())
    icons = board_icons["coins"]
    for symbol, image_id in icons.items():
        image_path = board_icons["images"].get(image_id)
        if not image_path or not (icon_root / image_path).is_file():
            raise ValueError(f"Missing firmware icon image: {symbol}")
    max_tokens = max(map(len, tokens.values()))
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/generate_address_catalog.py from the app catalog.",
        "#pragma once",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace airlock {",
        "struct AddressCatalogToken {",
        "    std::string_view symbol;",
        "    bool pending;",
        "};",
        "",
        "struct AddressCatalogEntry {",
        "    std::string_view firmware_name, label, native;",
        "    bool standalone;",
        f"    std::array<AddressCatalogToken, {max_tokens}> tokens;",
        "};",
        "",
        "inline constexpr AddressCatalogEntry address_catalog[] = {",
    ]
    for coin, label, native in networks:
        assets = tokens[coin]
        symbols = [native] + [symbol for symbol, _ in assets]
        if len(set(symbols)) != len(symbols) or any(symbol not in icons for symbol in symbols):
            raise ValueError(f"Duplicate asset or missing firmware icon in {coin}")
        names = ", ".join(map(json.dumps, (FIRMWARE_NAMES.get(coin, label), label, native)))
        rows = ", ".join(
            f"{{{json.dumps(symbol)}, {str(pending).lower()}}}" for symbol, pending in assets
        )
        entries = "{{" + rows + "}}" if assets else "{}"
        lines.append(f"    {{{names}, {str(coin in standalone).lower()}, {entries}}},")
    return "\n".join(lines + ["};", "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ESP32 / "ui/address_catalog.hpp"
    catalog = generate()
    if args.check:
        if output.read_text() != catalog:
            raise SystemExit(
                "Run tools/generate_address_catalog.py to sync the firmware catalog with the app."
            )
    else:
        output.write_text(catalog)

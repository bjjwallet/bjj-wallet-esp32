#!/usr/bin/env python3
"""Deterministic resize/encoding of the supplied artwork; no generated redraw."""

import hashlib
import json
import pathlib
import sys
from PIL import Image, ImageOps

source = pathlib.Path(sys.argv[1])
destination = pathlib.Path(__file__).resolve().parents[1] / "ui/assets"
destination.mkdir(parents=True, exist_ok=True)
image = Image.open(source).convert("RGBA")
image = ImageOps.contain(image, (224, 224), Image.Resampling.LANCZOS)
canvas = Image.new("RGBA", (224, 224), (0, 0, 0, 255))
canvas.alpha_composite(image, ((224 - image.width) // 2, (224 - image.height) // 2))
preview = canvas.convert("RGB")
preview.save(destination / "splash_preview.png", optimize=True)
data = bytearray()
for red, green, blue in preview.getdata():
    color = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
    data.extend((color & 255, color >> 8))
lines = [
    "// Generated by tools/prepare_splash.py from the supplied artwork.",
    '#include "splash_image.h"',
    "LV_ATTRIBUTE_MEM_ALIGN static const uint8_t splash_pixels[] = {",
]
for offset in range(0, len(data), 24):
    lines.append("    " + ",".join(f"0x{byte:02x}" for byte in data[offset : offset + 24]) + ",")
lines.extend(
    [
        "};",
        "const lv_image_dsc_t airlock_splash_image = {",
        "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,",
        "               .flags = 0, .w = 224, .h = 224, .stride = 448},",
        f"    .data_size = {len(data)}, .data = splash_pixels,",
        "};",
        "",
    ]
)
(destination / "splash_image.c").write_text("\n".join(lines))
(destination / "splash_manifest.json").write_text(
    json.dumps(
        {
            "source_name": source.name,
            "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "width": 224,
            "height": 224,
            "format": "RGB565 little endian, opaque black background",
            "flash_data_bytes": len(data),
            "pixel_sha256": hashlib.sha256(data).hexdigest(),
            "conversion": "Pillow 11.3.0, Lanczos containment; source artwork preserved",
        },
        indent=2,
        ensure_ascii=False,
    )
    + "\n"
)
print(f"Splash prepared: 224x224 RGB565, {len(data)} bytes embedded in flash.")
